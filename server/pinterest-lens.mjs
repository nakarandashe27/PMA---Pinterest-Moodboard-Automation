import { AppError } from './domain.mjs';

export const lensButtonName=/Search by image|Search with an image|Search image|Lens|Поиск по изображению|Поиск по фото/i;

export async function startPinterestLens(page,upload,{checkAccess,phase,diagnose,timeout=15000,chooserTimeout=1200,resultTimeout=35000}){
  const lens=page.getByRole('button',{name:lensButtonName}).first();
  const search=page.getByRole('button',{name:'Search icon',exact:true});
  try{
    await phase('Открываем поиск по фото Pinterest…');
    // Desktop Pinterest can collapse the whole search bar to this button.
    // Wait for the rendered controls instead of checking count immediately
    // after DOMContentLoaded, when Pinterest may still be an empty shell.
    await lens.or(search).first().waitFor({state:'visible',timeout});
    await checkAccess();
    if(!await lens.isVisible())await search.click();
    await lens.waitFor({state:'visible',timeout});
    await checkAccess();
    await phase('Открываем Pinterest Lens…');
    // Use the file chooser generated by the Lens control when available.
    // Some versions instead mount a hidden image input in the Lens panel.
    const chooserPromise=page.waitForEvent('filechooser',{timeout:chooserTimeout}).catch(()=>null);
    await lens.click();
    const chooser=await chooserPromise;
    await checkAccess();
    await phase('Передаём исходное фото в Pinterest Lens…');
    if(chooser)await chooser.setFiles(upload.path);
    else{
      const input=page.locator('input[type="file"][accept*="image"]').first();
      await input.waitFor({state:'attached',timeout});
      await input.setInputFiles(upload.path);
    }
    await phase('Ждём результаты Pinterest Lens…');
    await page.waitForURL(url=>/^\/(lens-search|visual-search)(\/|$)/.test(url.pathname),{timeout:resultTimeout});
    await checkAccess();
    return {strategy:'pinterest-lens',seedUploadId:upload.id,resultPath:new URL(page.url()).pathname,confirmedAt:new Date().toISOString()};
  }catch(error){
    await checkAccess();
    await diagnose();
    if(error instanceof AppError)throw error;
    throw new AppError('Не удалось запустить Pinterest Lens и получить визуальную выдачу. Откройте Pinterest и проверьте поиск по фото. Текстовый поиск вместо Lens не выполнялся.',409);
  }
}
